"""REST API around the RAG pipeline.

Run:   uvicorn docqa.api:app --reload
Docs:  http://127.0.0.1:8000/docs  (interactive Swagger page, generated by FastAPI)
"""

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from docqa.answer import answer
from docqa.llm import CHAT_MODEL, EMBED_MODEL, OllamaError
from docqa.prompts import DEFAULT_PROMPT, PROMPTS

app = FastAPI(
    title="DocQA",
    description="Ask questions about the NIST AI Risk Management Framework (AI RMF 1.0).",
    version="0.1.0",
)


class AskRequest(BaseModel):
    # Pydantic validates the JSON body: bad input gets a 422 before our code runs.
    question: str = Field(..., min_length=3, max_length=500, examples=["What are the four functions of the AI RMF core?"])
    k: int = Field(4, ge=1, le=10, description="How many passages to retrieve")
    prompt: str = Field(DEFAULT_PROMPT, description=f"One of: {', '.join(PROMPTS)}")


class Source(BaseModel):
    n: int
    page: str
    score: float
    text: str


class AskResponse(BaseModel):
    question: str
    answer: str
    refused: bool
    sources: list[Source]
    prompt: str


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "chat_model": CHAT_MODEL, "embed_model": EMBED_MODEL}


@app.post("/ask", response_model=AskResponse)
def ask(req: AskRequest) -> dict:
    if req.prompt not in PROMPTS:
        raise HTTPException(status_code=422, detail=f"Unknown prompt '{req.prompt}'. Use one of: {list(PROMPTS)}")
    try:
        return answer(req.question, k=req.k, prompt_name=req.prompt)
    except OllamaError as err:
        # The model server is down: a dependency failure, not a bug in the request.
        raise HTTPException(status_code=503, detail=str(err)) from err
    except FileNotFoundError as err:
        raise HTTPException(status_code=503, detail=str(err)) from err
